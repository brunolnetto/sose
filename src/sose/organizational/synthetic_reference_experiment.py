from __future__ import annotations

from pydantic import BaseModel, ConfigDict, InstanceOf

from .agency import AgencyLevel, AgencySpec
from .experiment import (
    CostAnalysisPlan,
    ExperimentProtocol,
    FalsificationRule,
    MetricDirection,
    MultipleComparisonMethod,
    OutcomeMetric,
    ParameterRange,
    ReplicationPlan,
    SamplingDesign,
    StatisticalPlan,
    SurrogateAnalysisPlan,
    SurrogateModel,
)
from .model_spec import (
    EvidenceClass,
    InterventionClass,
    ModelIntervention,
    ModelSpec,
)
from .synthetic_analysis import SyntheticRecoveryReport, analyze_reference_synthetic_experiment
from .synthetic_runner import SyntheticExperimentDataset, run_reference_synthetic_experiment
from .synthetic_study import SyntheticWorldSpec, generate_synthetic_worlds


REFERENCE_DESIGN_SEED_V1 = 20261007
REFERENCE_ROOT_SEED_V1 = 20261007


class ReferenceSyntheticExperimentDesignV1(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, arbitrary_types_allowed=True)

    design_seed: int
    root_seed: int
    baseline: InstanceOf[ModelSpec]
    protocol: InstanceOf[ExperimentProtocol]
    interventions: tuple[InstanceOf[ModelIntervention], ...]
    worlds: tuple[InstanceOf[SyntheticWorldSpec], ...]


class ReferenceSyntheticExperimentResultV1(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, arbitrary_types_allowed=True)

    design: InstanceOf[ReferenceSyntheticExperimentDesignV1]
    dataset: InstanceOf[SyntheticExperimentDataset]
    report: InstanceOf[SyntheticRecoveryReport]

    @property
    def report_hash(self) -> str:
        return self.report.report_hash


def build_reference_synthetic_experiment_v1() -> ReferenceSyntheticExperimentDesignV1:
    """Build the frozen synthetic benchmark used for mechanistic recovery."""

    baseline = ModelSpec(
        parameters={
            "arrival_rate": 0.8,
            "service_capacity": 1.0,
            "service_cv": 0.7,
            "rework_probability": 0.15,
            "transition_cost": 0.0,
        },
        parameter_evidence={
            name: EvidenceClass.ASSUMED
            for name in (
                "arrival_rate",
                "service_capacity",
                "service_cv",
                "rework_probability",
                "transition_cost",
            )
        },
        demand={"kind": "synthetic_open_system"},
        costs={"operating_cost": 1.0},
    )

    protocol = ExperimentProtocol(
        protocol_version="2",
        research_question=(
            "Can SOSE recover known queueing regimes and intervention directions "
            "from data generated by explicit exogenous organizational mechanics?"
        ),
        baseline_model_spec_hash=baseline.model_spec_hash,
        intervention_ids=("capacity-up", "automation-rework"),
        agency_levels=(AgencyLevel.A0,),
        parameter_ranges={
            "arrival_rate": ParameterRange(low=0.35, high=1.45),
            "service_capacity": ParameterRange(low=0.75, high=1.15),
            "service_cv": ParameterRange(low=0.20, high=1.20),
            "rework_probability": ParameterRange(low=0.00, high=0.40),
            "transition_cost": ParameterRange(low=0.0, high=10.0),
        },
        sampling_design=SamplingDesign.LATIN_HYPERCUBE,
        sample_size=12,
        outcomes=(
            OutcomeMetric(
                name="lead_time",
                direction=MetricDirection.MINIMIZE,
                equivalence_margin=0.05,
            ),
            OutcomeMetric(
                name="operating_cost",
                direction=MetricDirection.MINIMIZE,
                equivalence_margin=0.05,
            ),
        ),
        statistical_plan=StatisticalPlan(
            confidence_level=0.95,
            multiple_comparison=MultipleComparisonMethod.HOLM,
        ),
        replication_plan=ReplicationPlan(
            min_replications=16,
            max_replications=16,
            target_ci_half_width=0.10,
        ),
        cost_analysis=CostAnalysisPlan(
            operating_cost_metric="operating_cost",
            transition_cost_parameter="transition_cost",
        ),
        surrogate_analysis=SurrogateAnalysisPlan(model=SurrogateModel.LINEAR),
        warmup=200.0,
        horizon=1200.0,
        falsification=FalsificationRule(
            primary_metric="lead_time",
            theta_fraction=0.5,
        ),
    )

    interventions = (
        ModelIntervention(
            intervention_id="capacity-up",
            intervention_class=InterventionClass.CAPACITY,
            set_values={"/parameters/service_capacity": 1.6},
            operating_cost=0.35,
            transition_cost=2.0,
            transition_time=0.0,
        ),
        ModelIntervention(
            intervention_id="automation-rework",
            intervention_class=InterventionClass.AUTOMATION,
            set_values={"/parameters/rework_probability": 0.02},
            operating_cost=0.20,
            transition_cost=1.0,
            transition_time=0.0,
        ),
    )

    worlds = generate_synthetic_worlds(
        protocol=protocol,
        baseline=baseline,
        interventions=interventions,
        agency_specs={AgencyLevel.A0: AgencySpec(level=AgencyLevel.A0)},
        seed=REFERENCE_DESIGN_SEED_V1,
    )

    return ReferenceSyntheticExperimentDesignV1(
        design_seed=REFERENCE_DESIGN_SEED_V1,
        root_seed=REFERENCE_ROOT_SEED_V1,
        baseline=baseline,
        protocol=protocol,
        interventions=interventions,
        worlds=worlds,
    )


def run_reference_synthetic_experiment_v1() -> ReferenceSyntheticExperimentResultV1:
    """Run the complete fixed synthetic benchmark and recover known mechanics."""

    design = build_reference_synthetic_experiment_v1()
    dataset = run_reference_synthetic_experiment(
        protocol=design.protocol,
        worlds=design.worlds,
        root_seed=design.root_seed,
        replications=design.protocol.replication_plan.min_replications,
    )
    report = analyze_reference_synthetic_experiment(
        protocol=design.protocol,
        worlds=design.worlds,
        dataset=dataset,
    )
    return ReferenceSyntheticExperimentResultV1(
        design=design,
        dataset=dataset,
        report=report,
    )
